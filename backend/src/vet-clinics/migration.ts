import * as fs from 'fs';
import * as path from 'path';
import { Clinic } from './catalog';
import { readCityData } from '../cities/data-files';
import type { CityCatalog } from '../cities/catalog';

const quote = (v: string | number | boolean | null): string =>
  v === null ? 'NULL' : typeof v === 'string' ? "'" + v.replace(/'/g, "''") + "'" : String(v);
interface ImportedSeedRow {
  osm_id: number;
  osm_type: string;
  name_english: string | null;
  name_arabic: string | null;
  latitude: number;
  longitude: number;
  phone_number: string | null;
  address: string | null;
  website: string | null;
  city_hint: string | null;
  governorate_hint: string | null;
}
export const legacy = JSON.parse(
  fs.readFileSync(path.resolve(__dirname, '../database/data/vet_clinics_raw.json'), 'utf8'),
) as ImportedSeedRow[];
const oldCities = readCityData<CityCatalog>('neighbourhoods/district-seed.json.gz').records;
// Reproduce the old seeder's planar KNN and 3-decimal cache, against its frozen
// district catalog. An unknown/different historical City fails closed.
const cityCache = new Map<string, string>();
export const legacyCityCodes = legacy.map((c) => {
  const key = `${c.latitude.toFixed(3)}:${c.longitude.toFixed(3)}`;
  let code = cityCache.get(key);
  if (!code) {
    code = [...oldCities].sort(
      (a, b) =>
        (a.longitude - c.longitude) ** 2 +
        (a.latitude - c.latitude) ** 2 -
        ((b.longitude - c.longitude) ** 2 + (b.latitude - c.latitude) ** 2),
    )[0].sourceCode;
    cityCache.set(key, code);
  }
  return code;
});
const point = (c: { longitude: number; latitude: number }) =>
  `ST_SetSRID(ST_MakePoint(${c.longitude}, ${c.latitude}), 4326)`;
export function pristinePredicate(c: ImportedSeedRow, index: number): string {
  const ar = !!c.address && /[\u0600-\u06ff]/.test(c.address);
  const fields: Record<string, string | boolean | null> = {
    name_english: c.name_english,
    name_arabic: c.name_arabic,
    area_name: c.city_hint ?? c.governorate_hint ?? null,
    phone_number: c.phone_number,
    address: c.address,
    address_english: ar ? null : c.address,
    address_arabic: ar ? c.address : null,
    website: c.website,
    source: 'OSM',
    osm_type: c.osm_type,
    location_provenance: 'OSM',
    location_precision: 'street',
    is_active: true,
    facebook_url: null,
    is_24_hours: false,
  };
  return [
    `v.osm_id = ${c.osm_id}`,
    `v.source_key = ${quote(`OSM:${c.osm_type}/${c.osm_id}`)}`,
    ...Object.entries(fields).map(([k, v]) => `v.${k} IS NOT DISTINCT FROM ${quote(v)}`),
    `ST_AsEWKB(v.coordinates) = ST_AsEWKB(${point(c)})`,
    `v.city_id = (SELECT id FROM cities WHERE source_code = ${quote(legacyCityCodes[index])})`,
    'v.location_captured_at IS NULL',
    'v.updated_at = v.created_at',
    'NOT EXISTS (SELECT 1 FROM vet_clinic_location_audits a WHERE a.vet_clinic_id = v.id)',
  ].join(' AND\n      ');
}
function values(c: Clinic) {
  return {
    source_key: quote(c.sourceKey),
    name_english: quote(c.nameEnglish),
    name_arabic: quote(c.nameArabic),
    city_id: `(SELECT id FROM cities WHERE source_code = ${quote(c.cityId)})`,
    area_name: 'NULL',
    coordinates: point(c),
    phone_number: quote(c.phone),
    address: quote(c.addressArabic ?? c.addressEnglish),
    address_english: quote(c.addressEnglish),
    address_arabic: quote(c.addressArabic),
    website: quote(c.website),
    facebook_url: quote(c.facebookUrl),
    is_24_hours: quote(c.is24Hours),
    location_precision: quote(c.locationPrecision),
    source: quote(c.source),
    osm_id: c.osmEntities.length ? c.osmEntities[0].split('/')[1] : 'NULL',
    osm_type: c.osmEntities.length ? quote(c.osmEntities[0].split('/')[0]) : 'NULL',
    location_provenance: quote(c.source),
    is_active: quote(c.active),
  };
}
export function generateMigration(clinics: Clinic[], { firstRelease = false } = {}): string {
  const lines = [
    '-- Generated by src/vet-clinics/scripts/build.ts. Do not edit.',
    '-- Insert-only release. Only byte-identical original seed payloads may change.',
    'DO $release$',
    'DECLARE changed integer := 0; affected integer;',
    'BEGIN',
    '  PERFORM revision FROM city_catalog_revisions WHERE id = 1 FOR UPDATE;',
    "  IF NOT FOUND THEN RAISE EXCEPTION 'Missing catalog revision'; END IF;",
  ];
  for (const code of [...new Set(clinics.map((c) => c.cityId))].sort())
    lines.push(
      `  IF NOT EXISTS (SELECT 1 FROM cities WHERE source_code = ${quote(code)}) THEN RAISE EXCEPTION 'Missing City ${code}'; END IF;`,
    );
  if (firstRelease)
    legacy.forEach((old, index) => {
      const row = clinics.find((c) => c.osmEntities.includes(`${old.osm_type}/${old.osm_id}`));
      const fields = row ? values(row) : { is_active: 'false' };
      lines.push(
        `  UPDATE vet_clinics v SET ${Object.entries(fields)
          .map(([k, v]) => `${k} = ${v}`)
          .join(', ')}, updated_at = now()`,
        `    WHERE ${pristinePredicate(old, index)};`,
        '  GET DIAGNOSTICS affected = ROW_COUNT; changed := changed + affected;',
      );
    });
  for (const c of [...clinics].sort((a, b) => a.sourceKey.localeCompare(b.sourceKey))) {
    const fields = values(c);
    const ids = c.osmEntities.map((e) => e.split('/')[1]);
    lines.push(
      `  INSERT INTO vet_clinics (${Object.keys(fields).join(', ')})`,
      `    SELECT ${Object.values(fields).join(', ')}`,
      `    WHERE NOT EXISTS (SELECT 1 FROM vet_clinics WHERE source_key = ${quote(c.sourceKey)}${ids.length ? ` OR osm_id IN (${ids.join(', ')})` : ''})`,
      '    ON CONFLICT DO NOTHING;',
      '  GET DIAGNOSTICS affected = ROW_COUNT; changed := changed + affected;',
    );
  }
  lines.push(
    '  IF changed > 0 THEN',
    '    UPDATE city_catalog_revisions SET revision = revision + 1 WHERE id = 1;',
    '  END IF;',
    'END;',
    '$release$;',
    '',
  );
  return lines.join('\n');
}
